    imgs = []
    for name, n, slides in lib.PARTS:
        html = "\n\n".join(slides) + "\n"
        io.open(os.path.join(HERE, name + ".html"), "w", encoding="utf-8", newline="\n").write(html)
        print("   %-18s %3d 枚" % (name, len(slides)))
        total += len(slides)
        imgs += re.findall(r'src="img/([^"]+)\.png"', html)
        body.append("<!-- ========== %s（%d枚） ========== -->\n%s" % (name, len(slides), html.rstrip()))
    css = io.open(SKILL_CSS, encoding="utf-8").read() + "\n" + io.open(os.path.join(HERE, "deck.css"), encoding="utf-8").read()
